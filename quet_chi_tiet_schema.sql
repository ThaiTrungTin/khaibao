CREATE TABLE IF NOT EXISTS public.quet_chi_tiet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phieu_id BIGINT REFERENCES public.kiem_kho(id) ON DELETE CASCADE,
    ma_phieu TEXT NOT NULL,
    ma_vach TEXT NOT NULL,
    ten_hang_hoa TEXT,
    lot TEXT DEFAULT '-',
    date_expiry TEXT,
    so_luong NUMERIC(15,2) DEFAULT 1,
    user_name TEXT NOT NULL,
    branch TEXT NOT NULL,
    client_id TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

