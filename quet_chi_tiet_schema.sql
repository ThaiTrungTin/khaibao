CREATE OR REPLACE VIEW public.view_kiem_kho_tong_hop_chi_tiet AS
WITH scan_summary AS (
    SELECT 
        phieu_id,
        ma_phieu,
        ma_vach,
        COALESCE(lot, '-') AS lot,
        MAX(ten_hang_hoa) AS ten_hang_hoa,
        MAX(date_expiry) AS date_expiry,
        SUM(so_luong) AS tong_so_luong_quat,
        MAX(created_at) AS thoi_gian_quat_cuoi,
        jsonb_agg(DISTINCT jsonb_build_object('user_name', user_name, 'branch', branch)) AS scanners_json
    FROM public.quet_chi_tiet
    GROUP BY phieu_id, ma_phieu, ma_vach, COALESCE(lot, '-')
)
SELECT 
    COALESCE(q.phieu_id, c.phieu_id) AS phieu_id,
    COALESCE(q.ma_phieu, c.ma_phieu) AS ma_phieu,
    COALESCE(q.ma_vach, c.ma_vach) AS ma_vach,
    COALESCE(q.ten_hang_hoa, c.ten_hang_hoa) AS ten_hang_hoa,
    COALESCE(q.lot, c.lot, '-') AS lot,
    COALESCE(q.date_expiry, c.date_expiry) AS date_expiry,
    COALESCE(q.tong_so_luong_quat, c.so_luong_thuc_te, 0) AS so_luong_thuc_te,
    COALESCE(c.so_luong_he_thong, 0) AS so_luong_he_thong,
    (COALESCE(q.tong_so_luong_quat, c.so_luong_thuc_te, 0) - COALESCE(c.so_luong_he_thong, 0)) AS chenh_lech,
    CASE 
        WHEN COALESCE(q.tong_so_luong_quat, c.so_luong_thuc_te, 0) = COALESCE(c.so_luong_he_thong, 0) THEN 'KHOP'
        WHEN COALESCE(q.tong_so_luong_quat, c.so_luong_thuc_te, 0) > COALESCE(c.so_luong_he_thong, 0) THEN 'DU'
        ELSE 'THIEU'
    END AS trang_thai,
    COALESCE(q.scanners_json, jsonb_build_array(jsonb_build_object('user_name', c.user_name, 'branch', c.branch))) AS scanners,
    COALESCE(q.thoi_gian_quat_cuoi, c.thoi_gian_quat, c.created_at) AS thoi_gian_quat
FROM scan_summary q
FULL OUTER JOIN public.kiem_kho_chi_tiet c 
    ON (q.phieu_id = c.phieu_id OR q.ma_phieu = c.ma_phieu)
   AND q.ma_vach = c.ma_vach 
   AND q.lot = COALESCE(c.lot, '-');
